#!/usr/bin/env python3
"""Create Postgres tables from schema.sql and print row counts."""

from pathlib import Path

import psycopg2
from psycopg2 import sql

ROOT = Path(__file__).resolve().parent
TABLES = (
    "occupations",
    "age_groups",
    "genres",
    "users",
    "movies",
    "movie_genres",
    "ratings",
)


def load_database_url() -> str:
    env_path = ROOT / ".env"
    for line in env_path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        if key.strip() == "DATABASE_URL":
            return value.strip().strip("'\"")
    raise SystemExit("DATABASE_URL not found in .env")


def postgres_schema(raw: str) -> str:
    """Adapt the SQLite schema so it can run on Postgres."""
    sql_text = raw.replace("PRAGMA foreign_keys = ON;", "")
    # SQLite INTEGER PRIMARY KEY autoincrements; genres INSERTs omit IDs.
    sql_text = sql_text.replace(
        "genre_id INTEGER PRIMARY KEY",
        "genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    return sql_text


def strip_line_comments(sql_text: str) -> str:
    """Remove -- comments so semicolons inside them are not treated as statement ends."""
    cleaned = []
    for line in sql_text.splitlines():
        in_string = False
        i = 0
        out = []
        while i < len(line):
            ch = line[i]
            if ch == "'" and not in_string:
                in_string = True
                out.append(ch)
            elif ch == "'" and in_string:
                if i + 1 < len(line) and line[i + 1] == "'":
                    out.append("''")
                    i += 2
                    continue
                in_string = False
                out.append(ch)
            elif not in_string and ch == "-" and i + 1 < len(line) and line[i + 1] == "-":
                break
            else:
                out.append(ch)
            i += 1
        cleaned.append("".join(out))
    return "\n".join(cleaned)


def split_statements(sql_text: str) -> list[str]:
    return [part.strip() for part in strip_line_comments(sql_text).split(";") if part.strip()]


def main() -> None:
    dsn = load_database_url()
    schema_sql = postgres_schema((ROOT / "schema.sql").read_text())
    statements = split_statements(schema_sql)

    conn = psycopg2.connect(dsn)
    try:
        conn.autocommit = False
        with conn.cursor() as cur:
            for stmt in statements:
                cur.execute(stmt)
            print("Tables created.\n")
            print(f"{'table':<16} {'rows':>8}")
            print("-" * 26)
            for table in TABLES:
                cur.execute(
                    sql.SQL("SELECT COUNT(*) FROM {}").format(
                        sql.Identifier(table)
                    )
                )
                (count,) = cur.fetchone()
                print(f"{table:<16} {count:>8}")
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()
